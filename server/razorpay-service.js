/**
 * FrameLab Razorpay Payment Gateway Service
 * Secure order generation, cryptographic signature validation & webhook processing
 */

import https from 'https';
import crypto from 'crypto';

export class RazorpayService {
  constructor(config = {}) {
    this.keyId = config.keyId || process.env.RAZORPAY_KEY_ID || '';
    this.keySecret = config.keySecret || process.env.RAZORPAY_KEY_SECRET || '';
    this.webhookSecret = config.webhookSecret || process.env.RAZORPAY_WEBHOOK_SECRET || '';
    this.isTestMode = config.testMode !== undefined 
      ? config.testMode 
      : (process.env.RAZORPAY_TEST_MODE !== 'false');

    this.apiUrl = 'api.razorpay.com';
  }

  // Public Configuration safe for frontend exposure (NEVER expose keySecret or webhookSecret)
  getPublicConfig() {
    return {
      keyId: this.keyId,
      currency: 'INR',
      testMode: this.isTestMode,
      companyName: process.env.STORE_NAME || 'FrameLab Haute Eyewear'
    };
  }

  /**
   * Creates an official payment order via Razorpay API (or Sandbox Simulator in test mode)
   */
  async createOrder({ amountInPaise, currency = 'INR', receipt, notes = {} }) {
    if (!amountInPaise || amountInPaise <= 0) {
      throw new Error('Invalid order amount: amount must be greater than zero.');
    }

    const payload = JSON.stringify({
      amount: Math.round(amountInPaise),
      currency: currency.toUpperCase(),
      receipt: String(receipt).slice(0, 40),
      notes: {
        store: 'FrameLab Haute Eyewear',
        ...notes
      }
    });

    // Check if real credentials exist (not placeholder)
    const isPlaceholder = !this.keyId || this.keyId.includes('YOUR_KEY') || this.keySecret.includes('YOUR_KEY');

    if (isPlaceholder && !this.isTestMode) {
      throw new Error('Production Razorpay credentials missing. Set valid RAZORPAY_KEY_ID and RAZORPAY_KEY_SECRET.');
    }

    // If placeholder or in test mode, try Razorpay API; if credentials fail, fall back to high-fidelity test sandbox
    try {
      if (!isPlaceholder) {
        return await this._callRazorpayApi('/v1/orders', 'POST', payload);
      }
    } catch (err) {
      if (!this.isTestMode) {
        throw err;
      }
      console.warn('[RazorpayService] Live API call with test keys returned error, using Sandbox Simulation:', err.message);
    }

    // High-fidelity Sandbox Simulation for local test mode
    const simulatedOrderId = `order_sim_${Date.now().toString(36)}_${crypto.randomBytes(4).toString('hex')}`;
    return {
      id: simulatedOrderId,
      entity: 'order',
      amount: Math.round(amountInPaise),
      amount_paid: 0,
      amount_due: Math.round(amountInPaise),
      currency: currency.toUpperCase(),
      receipt: receipt,
      status: 'created',
      attempts: 0,
      notes: notes,
      created_at: Math.floor(Date.now() / 1000),
      _isSimulated: true
    };
  }

  /**
   * Cryptographically verifies Razorpay Payment Signature
   * Signature is generated by HMAC-SHA256(order_id + "|" + payment_id, secret)
   */
  verifyPaymentSignature({ razorpayOrderId, razorpayPaymentId, razorpaySignature }) {
    if (!razorpayOrderId || !razorpayPaymentId || !razorpaySignature) {
      return {
        isValid: false,
        error: 'Missing order_id, payment_id, or signature in verification payload'
      };
    }

    try {
      const dataToSign = `${razorpayOrderId}|${razorpayPaymentId}`;
      const expectedSignature = crypto
        .createHmac('sha256', this.keySecret)
        .update(dataToSign)
        .digest('hex');

      // Constant-time comparison to prevent timing attacks
      const expectedBuf = Buffer.from(expectedSignature, 'utf-8');
      const receivedBuf = Buffer.from(razorpaySignature, 'utf-8');

      if (expectedBuf.length !== receivedBuf.length) {
        return { isValid: false, error: 'Signature length mismatch' };
      }

      const isValid = crypto.timingSafeEqual(expectedBuf, receivedBuf);
      return {
        isValid,
        expectedSignature,
        error: isValid ? null : 'Cryptographic signature mismatch'
      };
    } catch (err) {
      return { isValid: false, error: err.message };
    }
  }

  /**
   * Generates a test signature for simulated test-mode payments
   */
  generateTestSignature(orderId, paymentId) {
    return crypto
      .createHmac('sha256', this.keySecret)
      .update(`${orderId}|${paymentId}`)
      .digest('hex');
  }

  /**
   * Cryptographically verifies official Razorpay Webhook Signatures
   */
  verifyWebhookSignature(rawBody, signatureHeader) {
    if (!this.webhookSecret) {
      console.warn('[RazorpayService] RAZORPAY_WEBHOOK_SECRET is not configured.');
      return false;
    }

    if (!signatureHeader || !rawBody) {
      return false;
    }

    try {
      const expectedSignature = crypto
        .createHmac('sha256', this.webhookSecret)
        .update(rawBody)
        .digest('hex');

      const expectedBuf = Buffer.from(expectedSignature, 'utf-8');
      const receivedBuf = Buffer.from(signatureHeader, 'utf-8');

      if (expectedBuf.length !== receivedBuf.length) {
        return false;
      }

      return crypto.timingSafeEqual(expectedBuf, receivedBuf);
    } catch (err) {
      console.error('[RazorpayService] Webhook signature verification error:', err.message);
      return false;
    }
  }

  /**
   * Internal HTTPS client helper for official Razorpay API calls
   */
  _callRazorpayApi(endpoint, method, payload) {
    return new Promise((resolve, reject) => {
      const auth = Buffer.from(`${this.keyId}:${this.keySecret}`).toString('base64');

      const options = {
        hostname: this.apiUrl,
        port: 443,
        path: endpoint,
        method: method,
        headers: {
          'Content-Type': 'application/json',
          'Authorization': `Basic ${auth}`,
          'Content-Length': Buffer.byteLength(payload)
        }
      };

      const req = https.request(options, (res) => {
        let body = '';
        res.on('data', chunk => body += chunk);
        res.on('end', () => {
          try {
            const parsed = JSON.parse(body);
            if (res.statusCode >= 200 && res.statusCode < 300) {
              resolve(parsed);
            } else {
              const errMsg = parsed.error ? parsed.error.description : `Razorpay API Error ${res.statusCode}`;
              reject(new Error(errMsg));
            }
          } catch (e) {
            reject(new Error(`Failed to parse Razorpay API response: ${body}`));
          }
        });
      });

      req.on('error', (err) => reject(err));
      req.write(payload);
      req.end();
    });
  }
}
